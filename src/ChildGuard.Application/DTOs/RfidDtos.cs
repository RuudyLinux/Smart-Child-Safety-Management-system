using ChildGuard.Domain.Enums;

namespace ChildGuard.Application.DTOs;

public record RfidCardListItemDto(
    int RfidCardId, string MaskedCardUid, RfidCardStatus Status,
    int? StudentId, string? StudentName, DateTime? AssignedAt);

public record RfidCardDetailDto(
    int RfidCardId, string MaskedCardUid, RfidCardStatus Status,
    int? StudentId, string? StudentName, string? StudentGrade, DateTime? AssignedAt, DateTime CreatedAt,
    IReadOnlyList<RfidCardAssignmentDto>? History = null, bool CanDelete = false);

public record AssignRfidRequest(string CardUid, int StudentId);

/// <summary>Adds a card to the inventory without giving it to anyone.</summary>
public record RegisterRfidCardRequest(string CardUid);

/// <summary>Gives a registered, active, unassigned card to a student who has none.</summary>
public record AssignRegisteredCardRequest(int StudentId);

/// <param name="NewStatus">Optional new condition for the card (e.g. Lost, Damaged, Retired) set in the same step.</param>
public record UnassignRfidRequest(string Reason, RfidCardStatus? NewStatus = null);

/// <summary>Swaps the student's card for another (registered spare or a new UID). The old card gets <paramref name="OldCardStatus"/>.</summary>
public record ReplaceRfidRequest(string NewCardUid, RfidCardStatus OldCardStatus, string Reason);

/// <summary>Moves a card from its current student to another student who has no card.</summary>
public record ReassignRfidRequest(int StudentId, string Reason);

public record RfidCardAssignmentDto(
    long Id, int StudentId, string? StudentName, DateTime? AssignedAt, DateTime? EndedAt, string? EndReason,
    bool IsMigratedSnapshot, string? AssignedBy, string? EndedBy);

public record RfidOperationResultDto(string Message, int RfidCardId, int? StudentId);

public record UpdateRfidStatusRequest(RfidCardStatus Status);

/// <param name="HasCredential">True when the scanner has its own API key issued (never exposes the key).</param>
public record RfidDeviceDto(int RfidDeviceId, string DeviceLabel, RfidConnectionStatus ConnectionStatus, DateTime? LastSeenAt,
    bool HasCredential = false, DateTime? CredentialIssuedAt = null);

/// <param name="ScanId">
/// Optional idempotency key for this physical tap (max 64 chars), generated by the
/// scanner and reused on retries. Omit it and the 120-second duplicate window still applies.
/// </param>
public record RfidScanRequest(string CardUid, int RfidDeviceId, JourneyEventType Checkpoint, string? ScanId = null);

/// <param name="EventRecorded">True when the checkpoint is on record — newly, or already (see AlreadyRecorded).</param>
/// <param name="AlreadyRecorded">
/// True when nothing new was written because this tap repeats one recorded moments ago
/// (same checkpoint within the duplicate window, or a retried ScanId).
/// </param>
public record RfidScanResultDto(
    bool StudentIdentified,
    int? StudentId,
    string? StudentName,
    string? MaskedCardUid,
    bool EventRecorded,
    JourneyEventType? RecordedEventType,
    string Message,
    bool AlreadyRecorded = false);

/// <summary>
/// Read-only card lookup for the pickup desk: who does this card belong to? Unlike a
/// scan it records nothing — at a pickup checkpoint the handover approval is the only
/// writer of the departure.
/// </summary>
public record RfidIdentifyRequest(string CardUid, int RfidDeviceId);

public record RfidIdentifyResultDto(
    bool StudentIdentified,
    int? StudentId,
    string? StudentName,
    string? MaskedCardUid,
    string Message);

/// <summary>Returned once when a scanner credential is issued; the key is not retrievable afterwards.</summary>
public record DeviceCredentialDto(int RfidDeviceId, string DeviceLabel, string ApiKey, DateTime IssuedAt);

public record CreateRfidDeviceRequest(string DeviceLabel);
public record UpdateRfidDeviceRequest(string DeviceLabel);

/// <summary>
/// The checkpoint chosen automatically for a card, from today's school schedule and the student's journey so far.
/// Nothing is recorded; the desk then records it (or starts guardian verification for a school departure).
/// </summary>
/// <param name="Checkpoint">Null when the journey is complete for today or the card cannot be used.</param>
public record NextCheckpointDto(
    bool StudentIdentified, int? StudentId, string? StudentName, string? MaskedCardUid,
    JourneyEventType? Checkpoint, string? CheckpointLabel, string Reason, bool OffSchedule);

/// <summary>School-wide card figures for the RFID page header, in one call (same meaning as the list filters).</summary>
public record RfidCardSummaryDto(int Total, int Active, int LostOrDamaged, int AvailableSpare, int Unassigned);
